const FALLBACK = 'en-US';

export function detectLocale(appLocale = '{{APP_LOCALE}}') {
  const browserLocale = navigator.languages?.[0] || navigator.language || FALLBACK;
  const preferred = appLocale && appLocale !== '{{APP_LOCALE}}' ? appLocale : browserLocale;
  if (TRANSLATIONS[preferred]) return preferred;
  const language = preferred.split('-')[0];
  const fallbackKey = Object.keys(TRANSLATIONS).find((key) => key.startsWith(language + '-'));
  return fallbackKey || FALLBACK;
}

export function createTranslator(locale) {
  return function t(key) {
    const bundle = TRANSLATIONS[locale];
    if (bundle && key in bundle) return bundle[key];
    return TRANSLATIONS[FALLBACK][key] || key;
  };
}

export function applyTranslations(root, t) {
  root.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.getAttribute('data-i18n');
    node.textContent = t(key);
  });

  root.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    const key = node.getAttribute('data-i18n-placeholder');
    const translation = t(key);
    if ('placeholder' in node) {
      node.setAttribute('placeholder', translation);
    }
  });
}
